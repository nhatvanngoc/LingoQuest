unit_num = 1
for unit_slug, items in GRADE12_DATA.items():
    lines.append(f'  "{unit_slug}": [')
    for idx, item in enumerate(items):
        word, pos, vi, ipa, en_ex, vi_ex, colocs, img = item
        clean_id = f"v12-u{unit_num}-{word.lower().replace(' ', '-').replace('/', '-')}"
        audio = f"https://dict.youdao.com/dictvoice?audio={word.replace(' ', '+')}&type=2"
        lines.append('    {')
        lines.append(f'      id: {json.dumps(clean_id)},')
        lines.append(f'      word: {json.dumps(word)},')
        lines.append(f'      partOfSpeech: {json.dumps(pos)},')
        lines.append(f'      meaningVi: {json.dumps(vi)},')
        lines.append(f'      ipa: {json.dumps(ipa)},')
